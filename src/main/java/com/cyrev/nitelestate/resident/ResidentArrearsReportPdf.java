package com.cyrev.nitelestate.resident;

import com.cyrev.nitelestate.resident.dto.ResidentArrearsResponse;
import org.openpdf.text.Document;
import org.openpdf.text.DocumentException;
import org.openpdf.text.Element;
import org.openpdf.text.Font;
import org.openpdf.text.PageSize;
import org.openpdf.text.Paragraph;
import org.openpdf.text.Phrase;
import org.openpdf.text.Rectangle;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;
import org.openpdf.text.pdf.PdfWriter;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Renders the downloadable "Accounts in Arrears" report (see ResidentService.generateArrearsReportPdf)
 * — same brand colours as payment.PaymentReceiptPdf, duplicated here rather than shared since
 * each PDF class is self-contained (same convention as every other small duplication in this
 * codebase - see e.g. PaymentService.resolveLandlordResidentId's own comment on why).
 */
public final class ResidentArrearsReportPdf {

    private static final Color BRAND_GREEN = new Color(0x14, 0x5A, 0x32);
    private static final Color BRAND_GREEN_LIGHT = new Color(0xBF, 0xE3, 0xCC);
    private static final Color INK = new Color(0x1F, 0x2A, 0x24);
    private static final Color MUTED = new Color(0x6D, 0x7A, 0x73);
    private static final Color BORDER = new Color(0xE6, 0xEB, 0xE8);
    private static final Color HEADER_ROW_BG = new Color(0xF8, 0xFA, 0xF9);
    private static final ZoneId ESTATE_ZONE = ZoneId.of("Africa/Lagos");
    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("d MMM yyyy, h:mm a");

    private ResidentArrearsReportPdf() {
    }

    public static byte[] render(List<ResidentArrearsResponse> debtors, BigDecimal arrearsThreshold) {
        Document document = new Document(PageSize.A4, 40, 40, 0, 40);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try {
            PdfWriter.getInstance(document, out);
            document.open();

            document.add(headerBand());

            Paragraph title = new Paragraph("Accounts in Arrears Report", new Font(Font.HELVETICA, 18, Font.BOLD, INK));
            title.setSpacingBefore(28);
            title.setSpacingAfter(2);
            document.add(title);

            BigDecimal total = debtors.stream().map(ResidentArrearsResponse::outstanding).reduce(BigDecimal.ZERO, BigDecimal::add);
            Paragraph subtitle = new Paragraph(
                    "Generated " + ZonedDateTime.now(ESTATE_ZONE).format(DATE_FORMAT) + "  ·  " + debtors.size()
                            + " account(s)  ·  total outstanding " + formatAmount(total)
                            + "  ·  threshold " + formatAmount(arrearsThreshold),
                    new Font(Font.HELVETICA, 10, Font.NORMAL, MUTED));
            subtitle.setSpacingAfter(20);
            document.add(subtitle);

            if (debtors.isEmpty()) {
                document.add(new Paragraph("No accounts are currently in arrears.", new Font(Font.HELVETICA, 11, Font.ITALIC, MUTED)));
            } else {
                document.add(table(debtors));
            }

            Paragraph footer = new Paragraph(
                    "Generated by Nitel Estate Management System. Outstanding = issued invoices minus successful payments.",
                    new Font(Font.HELVETICA, 9, Font.ITALIC, MUTED));
            footer.setSpacingBefore(24);
            document.add(footer);

            document.close();
        } catch (DocumentException e) {
            throw new IllegalStateException("Failed to generate arrears report PDF", e);
        }
        return out.toByteArray();
    }

    private static PdfPTable table(List<ResidentArrearsResponse> debtors) {
        PdfPTable table = new PdfPTable(4);
        table.setWidthPercentage(100);
        try {
            table.setWidths(new float[]{2.4f, 1.3f, 1.6f, 1.4f});
        } catch (DocumentException e) {
            throw new IllegalStateException(e);
        }

        headerCell(table, "Resident");
        headerCell(table, "Property");
        headerCell(table, "Phone");
        headerCell(table, "Outstanding");

        for (ResidentArrearsResponse debtor : debtors) {
            bodyCell(table, debtor.fullName(), Element.ALIGN_LEFT);
            bodyCell(table, debtor.propertyHouseNumber() != null ? debtor.propertyHouseNumber() : "—", Element.ALIGN_LEFT);
            bodyCell(table, debtor.phone(), Element.ALIGN_LEFT);
            bodyCell(table, formatAmount(debtor.outstanding()), Element.ALIGN_RIGHT);
        }
        return table;
    }

    private static void headerCell(PdfPTable table, String label) {
        PdfPCell cell = new PdfPCell(new Phrase(label, new Font(Font.HELVETICA, 9, Font.BOLD, MUTED)));
        cell.setBackgroundColor(HEADER_ROW_BG);
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(BORDER);
        cell.setBorderWidth(1.2f);
        cell.setPadding(8);
        table.addCell(cell);
    }

    private static void bodyCell(PdfPTable table, String value, int alignment) {
        PdfPCell cell = new PdfPCell(new Phrase(value, new Font(Font.HELVETICA, 10, Font.NORMAL, INK)));
        cell.setHorizontalAlignment(alignment);
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(BORDER);
        cell.setPadding(7);
        table.addCell(cell);
    }

    private static PdfPTable headerBand() {
        PdfPTable header = new PdfPTable(1);
        header.setWidthPercentage(100);
        PdfPCell cell = new PdfPCell();
        cell.setBackgroundColor(BRAND_GREEN);
        cell.setBorder(Rectangle.NO_BORDER);
        cell.setPadding(22);
        cell.addElement(new Paragraph("Nitel Estate", new Font(Font.HELVETICA, 20, Font.BOLD, Color.WHITE)));
        Paragraph subtitle = new Paragraph("Estate Management System", new Font(Font.HELVETICA, 10, Font.NORMAL, BRAND_GREEN_LIGHT));
        subtitle.setSpacingBefore(3);
        cell.addElement(subtitle);
        header.addCell(cell);
        return header;
    }

    private static String formatAmount(BigDecimal amount) {
        return "₦" + String.format("%,.2f", amount);
    }
}
