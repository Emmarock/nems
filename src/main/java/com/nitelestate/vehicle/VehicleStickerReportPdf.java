package com.nitelestate.vehicle;

import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.WriterException;
import com.google.zxing.common.BitMatrix;
import com.google.zxing.qrcode.QRCodeWriter;
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel;
import org.openpdf.text.Document;
import org.openpdf.text.DocumentException;
import org.openpdf.text.Element;
import org.openpdf.text.Font;
import org.openpdf.text.Image;
import org.openpdf.text.PageSize;
import org.openpdf.text.Paragraph;
import org.openpdf.text.Phrase;
import org.openpdf.text.Rectangle;
import org.openpdf.text.pdf.PdfContentByte;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;
import org.openpdf.text.pdf.PdfTemplate;
import org.openpdf.text.pdf.PdfWriter;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Map;

/**
 * Renders the downloadable vehicle sticker register (see VehicleService.generateStickerReportPdf):
 * one row per active vehicle with its plate number, its gate QR code and its owner, so the
 * estate can share it with residents and print the annual stickers from it. Same brand colours
 * as resident.ResidentArrearsReportPdf (each PDF class is self-contained, by convention).
 *
 * <p>QR codes are drawn as vector squares rather than embedded bitmaps, so they stay sharp at
 * whatever size the sticker is printed.
 */
public final class VehicleStickerReportPdf {

    /** One row of the register. {@code scanUrl} is what the QR encodes — the same URL as the in-app pass. */
    public record Row(String plateNumber, String scanUrl, String ownerName, String houseNumber, String vehicleDescription) {
    }

    private static final Color BRAND_GREEN = new Color(0x14, 0x5A, 0x32);
    private static final Color BRAND_GREEN_LIGHT = new Color(0xBF, 0xE3, 0xCC);
    private static final Color INK = new Color(0x1F, 0x2A, 0x24);
    private static final Color MUTED = new Color(0x6D, 0x7A, 0x73);
    private static final Color BORDER = new Color(0xE6, 0xEB, 0xE8);
    private static final Color HEADER_ROW_BG = new Color(0xF8, 0xFA, 0xF9);
    private static final ZoneId ESTATE_ZONE = ZoneId.of("Africa/Lagos");
    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("d MMM yyyy, h:mm a");

    /** Printed QR size in points (~3.5cm) — comfortably scannable by a gate phone camera on a windscreen. */
    private static final float QR_SIZE = 100f;

    private VehicleStickerReportPdf() {
    }

    public static byte[] render(List<Row> rows) {
        Document document = new Document(PageSize.A4, 40, 40, 0, 40);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try {
            PdfWriter writer = PdfWriter.getInstance(document, out);
            document.open();

            document.add(headerBand());

            ZonedDateTime now = ZonedDateTime.now(ESTATE_ZONE);
            Paragraph title = new Paragraph("Vehicle Sticker Register " + now.getYear(), new Font(Font.HELVETICA, 18, Font.BOLD, INK));
            title.setSpacingBefore(28);
            title.setSpacingAfter(2);
            document.add(title);

            Paragraph subtitle = new Paragraph(
                    "Generated " + now.format(DATE_FORMAT) + "  ·  " + rows.size() + " active vehicle(s)",
                    new Font(Font.HELVETICA, 10, Font.NORMAL, MUTED));
            subtitle.setSpacingAfter(20);
            document.add(subtitle);

            if (rows.isEmpty()) {
                document.add(new Paragraph("No active vehicles are registered in the estate.", new Font(Font.HELVETICA, 11, Font.ITALIC, MUTED)));
            } else {
                document.add(table(writer.getDirectContent(), rows));
            }

            Paragraph footer = new Paragraph(
                    "Generated by Nitel Estate Management System. Each QR code is the vehicle's gate pass: security scans it "
                            + "to identify the vehicle and its owner. Print it onto the vehicle's sticker for the year.",
                    new Font(Font.HELVETICA, 9, Font.ITALIC, MUTED));
            footer.setSpacingBefore(24);
            document.add(footer);

            document.close();
        } catch (DocumentException e) {
            throw new IllegalStateException("Failed to generate vehicle sticker register PDF", e);
        }
        return out.toByteArray();
    }

    private static PdfPTable table(PdfContentByte canvas, List<Row> rows) throws DocumentException {
        PdfPTable table = new PdfPTable(4);
        table.setWidthPercentage(100);
        table.setWidths(new float[]{0.4f, 1.6f, 1.7f, 2.4f});
        table.setHeaderRows(1);

        headerCell(table, "#");
        headerCell(table, "Plate number");
        headerCell(table, "QR tag");
        headerCell(table, "Owner");

        int index = 1;
        for (Row row : rows) {
            textCell(table, String.valueOf(index++), new Font(Font.HELVETICA, 9, Font.NORMAL, MUTED));

            PdfPCell plate = baseCell();
            plate.addElement(new Paragraph(row.plateNumber(), new Font(Font.HELVETICA, 13, Font.BOLD, INK)));
            if (row.vehicleDescription() != null && !row.vehicleDescription().isBlank()) {
                plate.addElement(new Paragraph(row.vehicleDescription(), new Font(Font.HELVETICA, 9, Font.NORMAL, MUTED)));
            }
            table.addCell(plate);

            // The plate goes under the QR as well, so a QR cut out on its own is still identifiable.
            PdfPCell qr = baseCell();
            qr.setHorizontalAlignment(Element.ALIGN_CENTER);
            Image image = Image.getInstance(qrTemplate(canvas, row.scanUrl()));
            image.setAlignment(Element.ALIGN_CENTER);
            // A cell otherwise stretches an image to its full width; keep the QR at its intended print size.
            image.setWidthPercentage(0);
            image.scaleAbsolute(QR_SIZE, QR_SIZE);
            qr.addElement(image);
            Paragraph qrCaption = new Paragraph(row.plateNumber(), new Font(Font.HELVETICA, 8, Font.BOLD, INK));
            qrCaption.setAlignment(Element.ALIGN_CENTER);
            qr.addElement(qrCaption);
            table.addCell(qr);

            PdfPCell owner = baseCell();
            owner.addElement(new Paragraph(row.ownerName() != null ? row.ownerName() : "—", new Font(Font.HELVETICA, 11, Font.BOLD, INK)));
            if (row.houseNumber() != null) {
                owner.addElement(new Paragraph("House " + row.houseNumber(), new Font(Font.HELVETICA, 9, Font.NORMAL, MUTED)));
            }
            table.addCell(owner);
        }
        return table;
    }

    private static PdfTemplate qrTemplate(PdfContentByte canvas, String content) {
        BitMatrix matrix;
        try {
            matrix = new QRCodeWriter().encode(content, BarcodeFormat.QR_CODE, 0, 0,
                    Map.of(EncodeHintType.ERROR_CORRECTION, ErrorCorrectionLevel.M, EncodeHintType.MARGIN, 2));
        } catch (WriterException e) {
            throw new IllegalStateException("Failed to encode vehicle QR code", e);
        }
        int modules = matrix.getWidth();
        float module = QR_SIZE / modules;
        PdfTemplate template = canvas.createTemplate(QR_SIZE, QR_SIZE);
        template.setColorFill(Color.BLACK);
        for (int y = 0; y < modules; y++) {
            for (int x = 0; x < modules; x++) {
                if (matrix.get(x, y)) {
                    // PDF's origin is bottom-left; the matrix's is top-left.
                    template.rectangle(x * module, QR_SIZE - (y + 1) * module, module, module);
                }
            }
        }
        template.fill();
        return template;
    }

    private static PdfPCell baseCell() {
        PdfPCell cell = new PdfPCell();
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(BORDER);
        cell.setPadding(8);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        return cell;
    }

    private static void textCell(PdfPTable table, String value, Font font) {
        PdfPCell cell = new PdfPCell(new Phrase(value, font));
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(BORDER);
        cell.setPadding(8);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        table.addCell(cell);
    }

    private static void headerCell(PdfPTable table, String label) {
        PdfPCell cell = new PdfPCell(new Phrase(label, new Font(Font.HELVETICA, 9, Font.BOLD, MUTED)));
        cell.setBackgroundColor(HEADER_ROW_BG);
        cell.setBorder(Rectangle.BOTTOM);
        cell.setBorderColor(BORDER);
        cell.setBorderWidth(1.2f);
        cell.setPadding(8);
        table.addCell(cell);
    }

    private static PdfPTable headerBand() {
        PdfPTable header = new PdfPTable(1);
        header.setWidthPercentage(100);
        PdfPCell cell = new PdfPCell();
        cell.setBackgroundColor(BRAND_GREEN);
        cell.setBorder(Rectangle.NO_BORDER);
        cell.setPadding(22);
        cell.addElement(new Paragraph("Nitel Estate", new Font(Font.HELVETICA, 20, Font.BOLD, Color.WHITE)));
        Paragraph subtitle = new Paragraph("Estate Management System", new Font(Font.HELVETICA, 10, Font.NORMAL, BRAND_GREEN_LIGHT));
        subtitle.setSpacingBefore(3);
        cell.addElement(subtitle);
        header.addCell(cell);
        return header;
    }
}
